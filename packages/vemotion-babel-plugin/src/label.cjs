'use strict';
// Labels: a readable name appended to class names, from the variable,
// property, function, class or class field the styles are written in.
const nodePath = require('node:path');

const INVALID_CLASS_NAME_CHARACTERS = /[!"#$%&'()*+,./:;<=>?@[\]^`|}~{]/g;
const sanitize = part => part.trim().replace(INVALID_CLASS_NAME_CHARACTERS, '-');

/** Applies labelFormat ([local], [filename], [dirname], or a function). */
function formatLabel(name, labelFormat, filename) {
  if (!name) return null;
  const local = sanitize(name);
  if (!labelFormat) return local;
  if (typeof labelFormat === 'function') return labelFormat({name: local, path: filename});
  const parsed = nodePath.parse(filename);
  const dirname = nodePath.basename(parsed.dir);
  // index files are named after their directory.
  const file = parsed.name === 'index' ? dirname : parsed.name;
  return labelFormat.replace(/\[local\]/gi, local).replace(/\[filename\]/gi, sanitize(file)).replace(/\[dirname\]/gi, sanitize(dirname));
}

/** The name of an object property or method (not computed). */
function propertyName(path, t) {
  if ((!t.isObjectProperty(path) && !t.isObjectMethod(path)) || path.node.computed) return null;
  if (t.isIdentifier(path.node.key)) return path.node.key.name;
  if (t.isStringLiteral(path.node.key)) return path.node.key.value.replace(/\s+/g, '-');
  return null;
}

/** The name the expression is assigned to, or of the function it is in. */
function declaratorName(path, t) {
  const parent = path.findParent(p => p.isVariableDeclarator() || p.isAssignmentExpression() || p.isFunctionDeclaration() || p.isFunctionExpression() || p.isArrowFunctionExpression() || p.isObjectProperty() || p.isObjectMethod());
  if (!parent) return '';
  if (parent.isVariableDeclarator()) return t.isIdentifier(parent.node.id) ? parent.node.id.name : '';
  if (parent.isAssignmentExpression()) {
    const {left} = parent.node;
    if (t.isIdentifier(left)) return left.name;
    if (!t.isMemberExpression(left)) return '';
    // a.b.c = ... is labeled a-b-c.
    let name = '';
    for (let member = left; ; member = member.object) {
      if (!t.isIdentifier(member.property)) return '';
      name = member.property.name + (name ? `-${name}` : '');
      if (t.isIdentifier(member.object)) return `${member.object.name}-${name}`;
      if (!t.isMemberExpression(member.object)) return '';
    }
  }
  if (parent.isFunctionDeclaration()) return parent.node.id.name || '';
  if (parent.isFunctionExpression()) return parent.node.id ? parent.node.id.name || '' : declaratorName(parent, t);
  if (parent.isArrowFunctionExpression()) return declaratorName(parent, t);
  const property = propertyName(parent, t);
  if (property) return property;
  const declarator = parent.findParent(p => p.isVariableDeclarator());
  return declarator && declarator.get('id').isIdentifier() ? declarator.node.id.name : '';
}

function identifierName(path, t) {
  const property = propertyName(path.parentPath, t);
  if (property) return property;
  const classLike = path.findParent(p => t.isClassProperty(p) || t.isClass(p));
  if (classLike) {
    if (t.isClassProperty(classLike) && classLike.node.computed === false && t.isIdentifier(classLike.node.key)) return classLike.node.key.name;
    if (t.isClass(classLike) && classLike.node.id) return t.isIdentifier(classLike.node.id) ? classLike.node.id.name : '';
  }
  const name = declaratorName(path, t);
  // Names starting with _ were probably generated by Babel.
  return name.charAt(0) === '_' ? '' : name;
}

exports.getLabelFromPath = (path, state, t) => formatLabel(identifierName(path, t), state.opts.labelFormat, state.file.opts.filename);
