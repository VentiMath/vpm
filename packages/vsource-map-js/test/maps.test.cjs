'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const {SourceMapConsumer, SourceMapGenerator} = require('../index.cjs');
const controls = ['source-map-js','source-map-app'].map(name => require('../../../scripts/source-map-conformance/node_modules/'+name));
function build(api) {
  const generator = new api.SourceMapGenerator({sourceRoot:'../src',file:'app.css'});
  for(let i=0;i<256;i++) {
    const generated = {line:1+(i>>3),column:(i%8)*5};
    const original = {line:500-i,column:i%13};
    const source = i%2 ? '__proto__' : 'theme.css';
    generator.addMapping(i%11 ? {generated,original,source,name:'rule'+(i%3)} : {generated});
    generated.line = 999; original.column = 999;
  }
  generator.setSourceContent('__proto__','');
  generator.setSourceContent('theme.css','body{}');
  return generator.toJSON();
}
test('generated bytes, bias and original source text agree with app and current controls',()=>{
  const map=build({SourceMapGenerator}), consumer=new SourceMapConsumer(map);
  for(const control of controls){
    assert.deepEqual(map,build(control));
    const other=new control.SourceMapConsumer(map);
    for(let line=1;line<=33;line++)for(let column=0;column<=40;column++)for(const bias of [1,2]){
      const query={line,column,bias};
      assert.deepEqual(consumer.originalPositionFor(query),other.originalPositionFor(query));
    }
    assert.deepEqual(SourceMapGenerator.fromSourceMap(consumer).toJSON(),control.SourceMapGenerator.fromSourceMap(other).toJSON());
  }
  assert.equal(consumer.sourceContentFor('../src/__proto__'),'');
  assert.equal(consumer.sourceContentFor('unknown',true),null);
});
test('invalid segments fail consistently on repeated reads',()=>{
  for(const mappings of ['g','!','AA','ACAA','AAAAA','ggggggggggA']){
    const consumer=new SourceMapConsumer({version:3,sources:['a'],mappings});
    for(let i=0;i<2;i++)assert.throws(()=>consumer.originalPositionFor({line:1,column:0}));
  }
});
test('late insertions sort, generated-only segments end a trace, and empty lines stay unmapped',()=>{
  const generator=new SourceMapGenerator();
  generator.addMapping({generated:{line:4,column:4}});
  generator.addMapping({generated:{line:4,column:1},original:{line:10,column:1},source:'a'});
  const consumer=new SourceMapConsumer(generator.toString());
  for(const [line,column,source] of [[3,1,null],[4,2,'a'],[4,4,null],[5,2,null]])
    assert.equal(consumer.originalPositionFor({line,column}).source,source);
});

test('single-pass decode validates the tail before exposing a prefix and sorts backward segments',()=>{
  for(const suffix of [',',',;',',AAA',',AAAAAA',',gggggggE',',AΩAA']){
    const c=new SourceMapConsumer({version:3,sources:['a'],names:['x'],mappings:'AAAA;AAAA'+suffix});
    for(let retry=0;retry<2;retry++) assert.throws(()=>c.originalPositionFor({line:1,column:0}));
  }
  const c=new SourceMapConsumer({version:3,sources:['a'],mappings:'IAAA,F;'});
  const rows=[];c.eachMapping(m=>rows.push(m.generatedColumn));
  assert.deepEqual(rows,[2,4]);
  assert.equal(c.originalPositionFor({line:1,column:3}).source,null);
  assert.equal(c.originalPositionFor({line:1,column:4}).source,'a');
});
